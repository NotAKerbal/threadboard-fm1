import { chromium } from 'playwright';
import { existsSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';

const server=process.env.THREADBOARD_TEST_URL?null:spawn(process.execPath,['bridge/main.ts','--demo','--port','0'],{stdio:['ignore','pipe','inherit']});
const base=process.env.THREADBOARD_TEST_URL??(String((await once(server.stdout,'data'))[0]).match(/http:\/\/127\.0\.0\.1:\d+/)?.[0]);
if(!base)throw new Error('The browser-test simulator did not start');
const chrome='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser=await chromium.launch({headless:true,...(existsSync(chrome)?{executablePath:chrome}:{})});
mkdirSync('output/screenshots',{recursive:true});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1100,height:1000}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base);await page.locator('.thread-key').first().waitFor();
  await page.waitForFunction(()=>document.querySelector('#connection').textContent==='Demo mode');
  assert.equal(await page.locator('.thread-key').count(),27);
  assert.equal(await page.locator('.thread-key.black:not(:disabled)').count(),2);
  const white=[0,2,4,6,7,9,11,12,14,16,18,19,21,23,24,26];
  let state=await page.request.get(base+'/api/state').then(r=>r.json());
  assert(state.slots.filter(s=>s.threadId).every(s=>white.includes(s.key)));
  const question=state.slots.find(s=>s.status==='waiting');
  await page.locator(`.thread-key[data-key="${question.key}"]`).click();
  await page.waitForFunction(key=>document.querySelector('#key-number').textContent===String(key).padStart(2,'0'),white.indexOf(question.key)+1);
  assert.equal(await page.locator('#thread-state').textContent(),'NEEDS YOU');
  await page.getByRole('button',{name:'Settle thread'}).click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('pending requests'));
  state=await page.request.get(base+'/api/state').then(r=>r.json());assert.equal(state.slots[question.key].token,question.token);
  await page.getByRole('button',{name:'Finished',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#thread-state').textContent==='NEEDS YOU');
  await page.locator(`.thread-key[data-key="${question.key}"]`).click();
  await page.waitForFunction(()=>document.querySelector('#detail').textContent.startsWith('Done, awaiting settlement'));
  await page.getByRole('button',{name:'Settle thread'}).click();
  await page.waitForFunction(key=>document.querySelector(`.thread-key[data-key="${key}"]`).dataset.state==='empty',question.key);
  state=await page.request.get(base+'/api/state').then(r=>r.json());assert.equal(state.slots[question.key].threadId,null);
  const running=state.slots.find(s=>s.state==='working');
  await page.locator(`.thread-key[data-key="${running.key}"]`).click();
  await page.waitForFunction(key=>document.querySelector('#key-number').textContent===String(key).padStart(2,'0'),white.indexOf(running.key)+1);
  await page.getByRole('button',{name:'Stop work'}).click();
  await page.waitForFunction(()=>document.querySelector('#thread-state').textContent==='READY');
  state=await page.request.get(base+'/api/state').then(r=>r.json());assert.equal(state.slots[running.key].threadId,running.threadId);
  await page.getByRole('button',{name:'Working',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#thread-state').textContent==='WORKING');
  await page.getByRole('button',{name:'Needs me',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#question-panel').hidden);
  assert.equal(await page.locator('#send-answers').isDisabled(),true);
  await page.locator('.thread-key.black[data-key="1"]').click();
  await page.waitForFunction(()=>document.querySelector('#question-progress').textContent.includes('Question 2 of 2'));
  await page.locator('.thread-key.black[data-key="1"]').click();
  await page.waitForFunction(()=>document.querySelector('#send-answers').disabled===false);
  await page.locator('.thread-key.black[data-key="3"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.answer-option[aria-pressed="true"]').length===2);
  await page.screenshot({path:'output/screenshots/question-choices.png',fullPage:true});
  await page.getByRole('button',{name:'More options'}).click();
  await page.waitForFunction(()=>document.querySelector('#question-progress').textContent.includes('page 2/2'));
  assert.equal(await page.locator('.thread-key.black:not(:disabled)').count(),1);
  await page.locator('.thread-key.black[data-key="1"]').click();
  await page.waitForFunction(()=>document.querySelector('.answer-option').getAttribute('aria-pressed')==='true');
  await page.getByRole('button',{name:'Send answers'}).click();
  await page.waitForFunction(()=>document.querySelector('#question-panel').hidden);
  assert.equal(await page.locator('.thread-key.black:disabled').count(),11);
  state=await page.request.get(base+'/api/state').then(r=>r.json());assert.equal(state.slots[running.key].threadId,running.threadId);
  await page.screenshot({path:'output/screenshots/desktop.png',fullPage:true});
  await page.setViewportSize({width:375,height:850});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:'output/screenshots/mobile.png',fullPage:true});
  assert.equal(await page.locator('.thread-key[data-state="working"] .key-led').first().evaluate(el=>getComputedStyle(el).animationName),'none');
  assert.equal(await page.locator('.thread-key[data-state="attention"]:not(.black) .key-led').first().evaluate(el=>getComputedStyle(el).animationName),'attention');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.thread-key[data-state="attention"]:not(.black) .key-led').first().evaluate(el=>getComputedStyle(el).animationName),'none');
  assert.deepEqual(errors,[]);
  console.log('Browser flow passed: black-key single/multi choices, paging, explicit submission, question cleared, stable thread keys, open/stop/settle, mobile, reduced motion.');
} finally {await browser.close();server?.kill();}
